export function buildLocalReviewPreview(employees: EmployeeListItem[]): EmployeeReviewDirectoryResult {
  if (!employees.length) return { items: [], total: 0, page: 1, pageSize: 18 };

  return {
    items: previewReviews.map((review, index) => {
      const employee = employees[index % employees.length];
      return {
        id: `local-review-preview-${index + 1}`,
        ...review,
        publishedAt: new Date(Date.UTC(2026, 7, 20 - index)).toISOString(),
        employee: {
          slug: employee.slug,
          fullName: employee.fullName,
          position: employee.position,
          photoUrl: employee.photoUrl,
        },
      };
    }),
    total: previewReviews.length,
    page: 1,
    pageSize: 18,
  };
}
