export function faqItemToPlainAnswer(item: AgencyFaqItem) {
  return item.answer
    .map((block) => (block.type === "paragraph" ? block.text : block.items.join(" ")))
    .join(" ");
}

export function faqItemsToSchema(items: AgencyFaqItem[]) {
  return items.map((item) => ({
    question: item.question,
    answer: faqItemToPlainAnswer(item),
  }));
}
